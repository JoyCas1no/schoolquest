"""Жабка в стиле референса: метаболлы -> единая органическая сетка."""
import sys, math, os
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from lib import *


def main():
    reset_scene()
    GREEN = mat("frog_green", (0.24, 0.55, 0.24))
    YELLOW = mat("frog_belly", (0.93, 0.87, 0.18))

    parts = [
        # туловище
        (0, 0.10, 0.34, 0.34, 0.40, 0.26),
        (0, 0.28, 0.30, 0.28, 0.22, 0.20),
        # голова-плита + морда
        (0, -0.24, 0.40, 0.30, 0.24, 0.16),
        (0, -0.44, 0.36, 0.24, 0.13, 0.10),
        # бугры глаз
        (-0.15, -0.26, 0.53, 0.10, 0.10, 0.08),
        (0.15, -0.26, 0.53, 0.10, 0.10, 0.08),
        # задние бёдра (массивные, сложенные)
        (-0.34, 0.10, 0.28, 0.16, 0.24, 0.18),
        (0.34, 0.10, 0.28, 0.16, 0.24, 0.18),
        # голени вниз-вперёд
        (-0.38, -0.10, 0.14, 0.09, 0.16, 0.09),
        (0.38, -0.10, 0.14, 0.09, 0.16, 0.09),
        # стопы задних лап
        (-0.38, -0.26, 0.055, 0.09, 0.16, 0.045),
        (0.38, -0.26, 0.055, 0.09, 0.16, 0.045),
        # передние лапы: плечо, предплечье, ладонь
        (-0.20, -0.18, 0.30, 0.06, 0.08, 0.10),
        (0.20, -0.18, 0.30, 0.06, 0.08, 0.10),
        (-0.24, -0.26, 0.16, 0.05, 0.06, 0.11),
        (0.24, -0.26, 0.16, 0.05, 0.06, 0.11),
        (-0.25, -0.30, 0.05, 0.055, 0.075, 0.035),
        (0.25, -0.30, 0.05, 0.055, 0.075, 0.035),
    ]
    # пальцы (тонкие эллипсоиды)
    for side in (-1, 1):
        fx = side * 0.25   # передние
        hx = side * 0.38   # задние
        for i, a in enumerate((-0.5, -0.18, 0.15, 0.48)):
            # передние пальцы
            parts.append((fx + math.sin(a) * 0.075, -0.375 - abs(math.sin(a)) * 0.01,
                          0.032, 0.028, 0.055, 0.018))
            # задние пальцы длиннее
            parts.append((hx + math.sin(a) * 0.10, -0.43, 0.030, 0.032, 0.075, 0.02))

    body = metabody("FrogBody", parts, voxel=0.013, material=GREEN,
                    zones=[(YELLOW, (0, -0.5, -0.7), 0.28, 0.47)])

    root = empty("Root")
    body.parent = root
    meshes = [body]

    # глаза: белок + жёлтое кольцо + зрачок
    WHITE = mat("eye_white", (0.97, 0.97, 0.97), rough=0.25)
    IRIS = mat("eye_iris", (0.85, 0.75, 0.15), rough=0.35)
    PUP = mat("eye_pupil", (0.05, 0.05, 0.06), rough=0.2)
    for side, x in (("L", -0.15), ("R", 0.15)):
        w = uv(f"EyeW{side}", (x, -0.29, 0.575), (0.095, 0.09, 0.095), WHITE, 24, 18)
        ring = torus(f"Iris{side}", (x, -0.352, 0.585), 0.058, 0.022, IRIS,
                     rot=(math.pi / 2, 0, 0))
        p = uv(f"Pupil{side}", (x, -0.368, 0.59), (0.036, 0.024, 0.036), PUP, 16, 12)
        hl = uv(f"EyeH{side}", (x - 0.022, -0.378, 0.618), (0.012, 0.009, 0.012), WHITE, 10, 8)
        for o in (w, ring, p, hl):
            o.parent = root
            meshes.append(o)

    os.makedirs(OUT_DIR, exist_ok=True)
    export_glb(f"{OUT_DIR}/mon_frog.glb", [root] + meshes)
    preview("/tmp/prev_mon_frog.png", meshes, size=1.2)
    print("OK frog")


main()
